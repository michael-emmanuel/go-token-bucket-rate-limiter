// Package limiter implements an in-process token bucket rate limiter.
//
// The package has three layers, each usable on its own:
//
//   - Limiter is a single, thread-safe token bucket. It answers "may this
//     request proceed right now?" (Allow, AllowN, Take) or blocks until it may
//     (Wait, WaitN).
//   - PerUser keeps one Limiter per key (user ID, API key, IP address) and can
//     additionally charge every request against a shared global Limiter,
//     atomically and without token leakage. It also owns the lifecycle of the
//     per-key state (see PerUser.Cleanup and PerUser.RunCleanup).
//   - Middleware adapts PerUser to net/http and answers over-limit requests with
//     429 Too Many Requests and a Retry-After header.
//
// # Model
//
// A bucket holds at most Capacity tokens and gains Rate tokens per second.
// Every request removes one or more tokens. When the bucket cannot cover a
// request the request is rejected (or, for Wait, delayed). Capacity bounds the
// burst size; Rate bounds the sustained throughput.
//
// Tokens are not generated by a background goroutine. Each operation computes
// the tokens earned since the previous operation from the elapsed time
// ("lazy refill"), so an idle bucket costs no CPU.
//
// # Scope
//
// All state is local to the process. Running N instances behind a load
// balancer yields an effective limit of up to N times the configured limit.
// See docs/distributed-rate-limiting.md in the repository.
